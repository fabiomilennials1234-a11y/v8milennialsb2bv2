-- Dedicated ingress canary: receipts only. No cron, no routing/config change.
-- Service-only technical inbox; tenant identity is resolved before enqueue and
-- checked again here. Payload may contain provider tokens: never expose to UI.
CREATE TABLE public.whatsapp_ingress_events (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  enqueue_sequence bigint GENERATED ALWAYS AS IDENTITY UNIQUE,
  organization_id uuid NOT NULL REFERENCES public.organizations(id) ON DELETE CASCADE,
  instance_id uuid NOT NULL REFERENCES public.whatsapp_instances(id) ON DELETE CASCADE,
  event_key text NOT NULL,
  event_name text NOT NULL CHECK (event_name = 'messages_update'),
  payload jsonb NOT NULL CHECK (jsonb_typeof(payload) = 'object' AND octet_length(payload::text) <= 2097152),
  payload_bytes integer GENERATED ALWAYS AS (octet_length(payload::text)) STORED,
  path_instance_id text,
  status text NOT NULL DEFAULT 'pending' CHECK (status IN ('pending','processing','completed','dead_letter')),
  attempts integer NOT NULL DEFAULT 0 CHECK (attempts BETWEEN 0 AND 8),
  next_attempt_at timestamptz NOT NULL DEFAULT now(),
  lease_until timestamptz,
  lease_token uuid,
  last_error_code text,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  completed_at timestamptz
);
