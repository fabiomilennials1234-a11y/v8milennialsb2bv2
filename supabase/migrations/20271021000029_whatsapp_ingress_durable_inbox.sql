CREATE INDEX whatsapp_ingress_events_due ON public.whatsapp_ingress_events(instance_id,next_attempt_at,created_at) WHERE status='pending';
CREATE INDEX whatsapp_ingress_events_leases ON public.whatsapp_ingress_events(instance_id,lease_until) WHERE status='processing';
CREATE INDEX whatsapp_ingress_events_retention ON public.whatsapp_ingress_events(completed_at) WHERE status='completed';
CREATE INDEX whatsapp_ingress_events_org ON public.whatsapp_ingress_events(organization_id);
CREATE INDEX whatsapp_ingress_events_fifo ON public.whatsapp_ingress_events(instance_id,enqueue_sequence) WHERE status IN ('pending','processing');

CREATE TABLE public.whatsapp_ingress_budget (
  singleton boolean PRIMARY KEY DEFAULT true CHECK(singleton),
  row_count bigint NOT NULL DEFAULT 0 CHECK(row_count>=0),
  payload_bytes bigint NOT NULL DEFAULT 0 CHECK(payload_bytes>=0)
);
