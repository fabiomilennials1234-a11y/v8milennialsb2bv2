CREATE INDEX CONCURRENTLY IF NOT EXISTS lead_history_whatsapp_message_id_idx ON public.lead_history USING hash ((metadata ->> 'message_id'::text)) WHERE ((metadata ->> 'channel'::text) = 'whatsapp'::text);
