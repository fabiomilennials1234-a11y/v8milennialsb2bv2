--   311 sem C1): menos UPDATE fora da página = menos cópia de linha. Com tupla
--   de ~1,36 kB (p50), 90 empacota igual a 100 (5/página) e não abre folga.
--   Ver .specs/perf/whatsapp-messages-indexes/README.md.
